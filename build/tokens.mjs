// Builds src/styles/theme.css (Tailwind v4) from tokens/*.json with Style Dictionary.
// CSS variable names come from each token's Figma WEB code syntax, so code and Figma always match.
import StyleDictionary from 'style-dictionary';

const BASE_PX = 16;
// Figma modes → CSS context. Default modes (Light, Desktop, single-mode collections) go in @theme.
const DARK_SELECTOR = '[data-theme="dark"]';
const MEDIA = { iPad: '(max-width: 1279px)', Mobile: '(max-width: 767px)' };
const BREAKPOINTS = { ipad: '48rem', desktop: '80rem' };
const FONT_FALLBACK = 'ui-sans-serif, system-ui, sans-serif';

const fig = t => t.$extensions?.['com.figma'] ?? {};
// "var(--text-color-primary)" → "--text-color-primary"; calc() syntax (space/1_5) has no own variable
const varName = t => fig(t).codeSyntax?.WEB.match(/^var\((--[\w-]+)\)$/)?.[1] ?? null;

function cssValue(t, raw, byPath) {
  if (typeof raw === 'string' && raw.startsWith('{')) {
    const target = byPath.get(raw.slice(1, -1));
    return `var(${varName(target)})`;
  }
  switch (t.$type) {
    case 'dimension': {
      const px = parseFloat(raw);
      if (px === 0) return '0';
      if (px >= 9999) return '9999px';
      // letter spacing stays in px as designed; sizes become rem so they follow user font scaling
      if (t.path[0] === 'letter-spacing') return `${px}px`;
      return `${px / BASE_PX}rem`;
    }
    case 'fontFamily': return `"${raw}", ${FONT_FALLBACK}`;
    case 'shadow':
      return raw.map(s => `${s.inset ? 'inset ' : ''}${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} ${s.color}`.replaceAll(/\b0px\b/g, '0')).join(', ');
    default: return String(raw);
  }
}

StyleDictionary.registerFormat({
  name: 'tailwind/theme-v4',
  format: ({ dictionary }) => {
    const byPath = new Map(dictionary.allTokens.map(t => [t.path.join('.'), t]));
    const theme = [], dark = [], media = { iPad: [], Mobile: [] };
    let group = null;

    for (const t of dictionary.allTokens) {
      const f = fig(t);
      const name = t.$type === 'shadow' ? `--${f.style}` : varName(t);
      if (!name) continue;
      const label = f.collection ?? 'Effects';
      if (label !== group) { theme.push(`\n  /* ${label} */`); group = label; }
      theme.push(`  ${name}: ${cssValue(t, t.original.$value, byPath)};`);
      // Tailwind pairs text-* with a default line height; tie each size to its own leading token
      if (t.path[0] === 'font-size') theme.push(`  ${name}--line-height: var(--leading-${t.path[1]});`);

      // original: Style Dictionary resolves references inside $extensions too, and we want var() links
      const modes = fig(t.original).modes;
      if (!modes) continue;
      if ('Dark' in modes && modes.Dark !== modes.Light) dark.push(`  ${name}: ${cssValue(t, modes.Dark, byPath)};`);
      if ('iPad' in modes && modes.iPad !== modes.Desktop) media.iPad.push(`    ${name}: ${cssValue(t, modes.iPad, byPath)};`);
      // Mobile block sits inside the iPad range too, so it only needs values that differ from iPad
      if ('Mobile' in modes && modes.Mobile !== modes.iPad) media.Mobile.push(`    ${name}: ${cssValue(t, modes.Mobile, byPath)};`);
    }

    return [
      '/* Generated by `npm run tokens:build` from tokens/*.json. Do not edit by hand. */',
      '@import "tailwindcss";',
      '',
      '@theme {',
      '  /* Only Trianglz colors exist: Tailwind\'s default palette is removed */',
      '  --color-*: initial;',
      ...Object.entries(BREAKPOINTS).map(([k, v]) => `  --breakpoint-${k}: ${v};`),
      ...theme,
      '}',
      '',
      `${DARK_SELECTOR} {`,
      '  color-scheme: dark;',
      ...dark,
      '}',
      '',
      ...Object.entries(media).flatMap(([mode, lines]) => [
        `/* ${mode} values */`,
        `@media ${MEDIA[mode]} {`,
        '  :root {',
        ...lines,
        '  }',
        '}',
        '',
      ]),
    ].join('\n');
  },
});

const sd = new StyleDictionary({
  source: ['tokens/tokens.json', 'tokens/effects.json'],
  log: { verbosity: 'default' },
  platforms: {
    tailwind: {
      // Unique internal names only; the CSS names come from Figma code syntax in the format above
      transforms: ['name/kebab'],
      buildPath: 'src/styles/',
      files: [{ destination: 'theme.css', format: 'tailwind/theme-v4' }],
    },
  },
});

await sd.buildAllPlatforms();
