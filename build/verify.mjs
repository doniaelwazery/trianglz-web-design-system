// Checks that every Figma WEB code syntax name exists in theme.css and that Tailwind
// generates the matching utility class. Exits 1 on any miss.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execSync } from 'node:child_process';

const tokens = JSON.parse(readFileSync('tokens/tokens.json', 'utf8'));
const effects = JSON.parse(readFileSync('tokens/effects.json', 'utf8'));
const theme = readFileSync('src/styles/theme.css', 'utf8');

function flatten(node, path = [], out = []) {
  if (node.$type) out.push({ path, ...node });
  else for (const [k, v] of Object.entries(node)) if (!k.startsWith('$')) flatten(v, [...path, k], out);
  return out;
}

// Order matters: longer prefixes first.
const RULES = [
  ['--text-color-', 'text-', 'color'],
  ['--background-color-', 'bg-', 'background-color'],
  ['--border-color-', 'border-', 'border-color'],
  ['--color-', 'bg-', 'background-color'],
  ['--text-', 'text-', 'font-size'],
  ['--leading-', 'leading-', 'line-height'],
  ['--tracking-', 'tracking-', 'letter-spacing'],
  ['--font-weight-', 'font-', 'font-weight'],
  ['--font-', 'font-', 'font-family'],
  ['--radius-', 'rounded-', 'border-radius'],
  ['--spacing-', 'p-', 'padding'],
  ['--inset-shadow-', 'inset-shadow-', null],
  ['--shadow-', 'shadow-', null],
];

const checks = [];
for (const t of [...flatten(tokens), ...flatten(effects)]) {
  const web = t.$extensions['com.figma'].codeSyntax.WEB;
  const v = web.match(/^var\((--[\w-]+)\)$/)?.[1];
  const calc = web.match(/^calc\(var\(--spacing\) \* ([\d.]+)\)$/)?.[1];
  if (v) {
    const [prefix, cls, prop] = RULES.find(([p]) => v.startsWith(p));
    checks.push({ web, variable: v, cls: cls + v.slice(prefix.length), prop, needsVar: prop !== null });
  } else if (calc) {
    checks.push({ web, variable: null, cls: `p-${calc}`, prop: 'padding', needsVar: false });
  } else checks.push({ web, error: 'unrecognised code syntax' });
}
// State variants used in components
checks.push({ web: 'hover state', cls: 'hover:bg-btn-primary-hover', prop: 'background-color', needsVar: false });

mkdirSync('src/test', { recursive: true });
writeFileSync('src/test/tokens.html', `<!-- Generated by build/verify.mjs: one element per token class. -->\n<div class="${checks.map(c => c.cls).filter(Boolean).join(' ')}"></div>\n`);
execSync('npx @tailwindcss/cli -i src/test/test.css -o dist/test.css', { stdio: 'pipe' });
const css = readFileSync('dist/test.css', 'utf8');

// Selector as Tailwind writes it in CSS: "p-1.5" → ".p-1\.5", "hover:x" → ".hover\:x"
const selector = cls => '.' + cls.replace(/[.:/]/g, m => '\\' + m);
// Rule body up to the first "}" (covers nested blocks like &:hover { @media (hover: hover) { … } })
function ruleBody(cls) {
  const sel = selector(cls);
  let i = css.indexOf(sel);
  while (i !== -1 && /[\w-]/.test(css[i + sel.length])) i = css.indexOf(sel, i + 1);
  return i === -1 ? null : css.slice(i, css.indexOf('}', i));
}
const failures = [];
for (const c of checks) {
  if (c.error) { failures.push(`${c.web}: ${c.error}`); continue; }
  if (c.variable && !new RegExp(`${c.variable}:`).test(theme)) failures.push(`${c.web}: ${c.variable} missing from theme.css`);
  const body = ruleBody(c.cls);
  if (!body) { failures.push(`${c.web}: class .${c.cls} not generated`); continue; }
  if (c.prop && !body.includes(`${c.prop}:`)) failures.push(`${c.web}: .${c.cls} does not set ${c.prop}`);
  if (c.needsVar && !body.includes(`var(${c.variable})`)) failures.push(`${c.web}: .${c.cls} does not use var(${c.variable})`);
}
for (const [label, re] of [['dark mode block', /\[data-theme="dark"\]\s*\{/], ['iPad block', /max-width: 1279px/], ['Mobile block', /max-width: 767px/]]) {
  if (!re.test(css)) failures.push(`${label} missing from compiled CSS`);
}

console.log(`Checked ${checks.length} token classes against Figma code syntax.`);
if (failures.length) {
  console.error(`${failures.length} problem(s):\n- ` + failures.join('\n- '));
  process.exit(1);
}
console.log('All Figma code syntax names exist in theme.css and generate Tailwind classes.');
